// Plays thousands of computer-vs-computer battles between random teams and
// reports how often each species ends up on the winning side, against the
// others of its tier (tiers are meant to differ). Same seed, same report.
//   npm run balance            # writes docs/BALANCE.md
//   npm run balance -- 2000    # fewer battles, for a quick look
import { writeFileSync } from "node:fs";
import { act, autoAction, makeBattle } from "../packages/shared/combat";
import { SPECIES } from "../packages/shared/content";
import type { Owned } from "../packages/shared/types";

const BATTLES = Number(process.argv[2]) || 20000,
  LEVEL = 20;
let seed = 20261108;
const random = () => {
  // mulberry32
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const team = (): Owned[] => {
  const pool = [...SPECIES],
    out: Owned[] = [];
  while (out.length < 6) {
    const s = pool.splice(Math.floor(random() * pool.length), 1)[0];
    out.push({ id: `${s.id}-${out.length}`, species: s.id, level: LEVEL, xp: 0, shards: 0, upgrade: 0, locked: false });
  }
  return out;
};
const stats = new Map<string, { games: number; wins: number }>(SPECIES.map((s) => [s.id, { games: 0, wins: 0 }]));
let draws = 0,
  turns = 0;
const started = Date.now();
for (let n = 0; n < BATTLES; n++) {
  const sides = [team(), team()],
    b = makeBattle(`sim-${n}`, sides, "pve", Math.floor(random() * 1e9));
  for (let turn = 0, now = 0; b.winner === null && turn < 600; turn++) {
    const actor = b.units.find((u) => u.id === b.queue[0]);
    if (!actor) break;
    const choice = autoAction(b);
    act(b, actor.side, choice.action, choice.target, (now += 5000), true);
  }
  turns += b.round;
  if (b.winner === null) draws++;
  sides.forEach((side, i) =>
    side.forEach((o) => {
      const s = stats.get(o.species)!;
      s.games++;
      if (b.winner === i) s.wins++;
    }),
  );
}
type Row = { id: string; name: string; tier: string; rate: number; games: number; z: number };
const rows: Row[] = SPECIES.map((s) => {
  const { games, wins } = stats.get(s.id)!;
  return { id: s.id, name: s.name, tier: s.tier, rate: wins / games, games, z: 0 };
});
const tiers = [...new Set(rows.map((r) => r.tier))];
const tierMean: Record<string, number> = {};
for (const tier of tiers) {
  const list = rows.filter((r) => r.tier === tier);
  tierMean[tier] = list.reduce((a, r) => a + r.rate, 0) / list.length;
  for (const r of list) r.z = (r.rate - tierMean[tier]) / Math.sqrt((r.rate * (1 - r.rate)) / r.games);
}
const pct = (x: number) => `${(x * 100).toFixed(1)}%`,
  line = (r: Row) => `| ${r.name} | ${r.tier} | ${pct(r.rate)} | ${r.rate >= tierMean[r.tier] ? "+" : ""}${((r.rate - tierMean[r.tier]) * 100).toFixed(1)} | ${r.games} |`;
const flagged = rows.filter((r) => Math.abs(r.z) > 3).sort((a, b) => b.z - a.z);
const tierOrder = ["S", "A", "B", "C", "D", "E"].filter((t) => tiers.includes(t));
const report = `# Balance report

Generated by \`npm run balance\` (\`scripts/balance.ts\`): ${BATTLES} battles between random teams of six distinct species, all at level ${LEVEL}, both sides played by the game's own auto-battler. ${draws} battles reached the turn limit without a winner, and the average battle lasted ${(turns / BATTLES).toFixed(1)} rounds. Tiers are meant to differ, so each species is compared with the average of its own tier. Win rate means how often a team containing it won; each species played about ${Math.round(rows.reduce((a, r) => a + r.games, 0) / rows.length)} battles, so differences of a few points are noise.

This measures the auto-battler's play, not a person's, and ignores equipment, skill levels and formation choices. Treat it as a pointer to what deserves a closer look, not a verdict.

## Tier averages

| Tier | Average win rate | Species |
| --- | --- | --- |
${tierOrder.map((t) => `| ${t} | ${pct(tierMean[t])} | ${rows.filter((r) => r.tier === t).length} |`).join("\n")}

## Clear outliers within their tier

More than three standard errors from their tier's average.

| Species | Tier | Win rate | Points from tier | Battles |
| --- | --- | --- | --- | --- |
${flagged.length ? flagged.map(line).join("\n") : "| (none) | | | | |"}

## Every species

| Species | Tier | Win rate | Points from tier | Battles |
| --- | --- | --- | --- | --- |
${tierOrder.flatMap((t) => rows.filter((r) => r.tier === t).sort((a, b) => b.rate - a.rate).map(line)).join("\n")}
`;
writeFileSync("docs/BALANCE.md", report);
console.log(`${BATTLES} battles (${(turns / BATTLES).toFixed(1)} rounds on average) in ${((Date.now() - started) / 1000).toFixed(1)} s, ${draws} unfinished; ${flagged.length} clear outliers:`);
for (const r of flagged) console.log(`  ${r.name} (${r.tier}) ${pct(r.rate)} vs tier ${pct(tierMean[r.tier])}`);
